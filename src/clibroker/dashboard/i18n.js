  const preferenceKey = "clibroker.language";
  function detectLanguage(preferences = [], stored = null) {
    if (Object.hasOwn(locales, stored)) return stored;
    for (const candidate of preferences) {
      const tag = String(candidate).toLowerCase();
      const exact = Object.keys(locales).find(code => code.toLowerCase() === tag);
      if (exact) return exact;
      const base = tag.split("-")[0];
      const related = Object.keys(locales).find(code => code.toLowerCase().split("-")[0] === base);
      if (related) return related;
    }
    return "en";
  }
  function text(language, key, values = {}) {
    const template = messages[language]?.[key] ?? messages.en[key];
    if (template === undefined) throw new Error(`Unknown translation key: ${key}`);
    return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
  }
  const api = { locales, messages, preferenceKey, detectLanguage, text };
